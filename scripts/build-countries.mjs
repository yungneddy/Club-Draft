// Generates src/data/countries.ts from the `world-countries` package.
// Run with `npm run countries` after upgrading world-countries.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const raw = JSON.parse(readFileSync(require.resolve('world-countries/countries.json'), 'utf8'));

// UN members plus a few widely recognised non-members that show up in flag quizzes.
const EXTRA = new Set(['XK', 'TW', 'PS']);

// Well-known countries: the "Easy" pool.
const TIER1 = `us ca mx br ar cl co pe gb ie fr de it es pt nl be ch at se no dk fi is pl gr tr ru ua
  cn jp kr in pk th vn id ph au nz za eg ng ke ma sa ae il jm cu sg`;
// Recognisable-ish: added for "Medium".
const TIER2 = `cz sk hu ro bg hr rs si ba me al mk ee lv lt by md lu mt cy ge am az kz uz af np bd lk mm kh
  la mn kp tw my qa kw jo lb sy ye om bh ir iq ve ec bo py uy cr pa gt hn ni sv do ht bs tt et gh sn
  ci cm tz ug zw zm ao mz dz tn ly sd so rw na bw mg fj pg`;

const tier1 = new Set(TIER1.split(/\s+/).filter(Boolean));
const tier2 = new Set(TIER2.split(/\s+/).filter(Boolean));

const NAME_OVERRIDES = { TR: 'Turkey' };
// Capital fixes where the dataset is ambiguous or people commonly name a second city.
const CAPITAL_OVERRIDES = {
  LK: { capital: 'Sri Jayawardenepura Kotte', also: ['Colombo'] },
  SZ: { capital: 'Mbabane', also: ['Lobamba'] },
  BO: { capital: 'Sucre', also: ['La Paz'] },
  ZA: { capital: 'Pretoria', also: ['Cape Town', 'Bloemfontein'] },
  NL: { capital: 'Amsterdam', also: ['The Hague (seat of government)'] },
  CI: { capital: 'Yamoussoukro', also: ['Abidjan (largest city)'] },
  BJ: { capital: 'Porto-Novo', also: ['Cotonou (seat of government)'] },
};
// Countries whose continent is genuinely debatable; skipped for continent questions.
const TRANSCONTINENTAL = new Set(['RU', 'TR', 'KZ', 'GE', 'AZ', 'AM', 'CY', 'EG']);
// Contested capitals; skipped for capital questions.
const CONTESTED_CAPITAL = new Set(['IL', 'PS']);

function continentOf(c) {
  if (c.region === 'Americas') return c.subregion === 'South America' ? 'South America' : 'North America';
  return c.region;
}

const included = raw.filter((c) => c.unMember || EXTRA.has(c.cca2));
const byCca3 = new Map(included.map((c) => [c.cca3, c.cca2.toLowerCase()]));
const rawByCca3 = new Map(raw.map((c) => [c.cca3, c]));
// Keep only land borders both countries agree on (the source lists Sri Lanka-India, a sea border, one way).
const landBorder = (c, b) => rawByCca3.get(b)?.borders?.includes(c.cca3);

const countries = included
  .map((c) => {
    const code = c.cca2.toLowerCase();
    const override = CAPITAL_OVERRIDES[c.cca2];
    const capital = override?.capital ?? c.capital?.[0] ?? '';
    const also = override?.also ?? (c.capital?.slice(1) ?? []);
    return {
      code,
      name: NAME_OVERRIDES[c.cca2] ?? c.name.common,
      capital,
      ...(also.length ? { capitalAlso: also } : {}),
      continent: continentOf(c),
      subregion: c.subregion,
      area: Math.round(c.area),
      landlocked: Boolean(c.landlocked),
      borders: (c.borders ?? [])
        .filter((b) => landBorder(c, b))
        .map((b) => byCca3.get(b))
        .filter(Boolean),
      tier: tier1.has(code) ? 1 : tier2.has(code) ? 2 : 3,
      ...(TRANSCONTINENTAL.has(c.cca2) ? { transcontinental: true } : {}),
      ...(CONTESTED_CAPITAL.has(c.cca2) ? { contestedCapital: true } : {}),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const missing = [...tier1, ...tier2].filter((code) => !countries.some((c) => c.code === code));
if (missing.length) throw new Error(`Tier codes not in dataset: ${missing.join(', ')}`);

const out = `// AUTO-GENERATED by scripts/build-countries.mjs from the world-countries package. Do not edit by hand.
import type { Country } from '../types';

export const COUNTRIES: Country[] = [
${countries.map((c) => `  ${JSON.stringify(c)},`).join('\n')}
];
`;
writeFileSync(new URL('../src/data/countries.ts', import.meta.url), out);
console.log(`Wrote ${countries.length} countries`);
